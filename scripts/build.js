// Copies the extension's static files next to the compiled TypeScript and
// writes the backend location into it.
//
//   node scripts/build.js [outDir] [--env development|staging|production]
//
// outDir defaults to compiled/; the environment to LAMISS_ENV, else
// development. Each environment's backend and Google client ID come from
// config/environments.json (see docs/RELEASING.md) and are written to
// shared/lamiss-config.js; the backend origin is added to the manifest's host
// permissions, and the WebSocket URL is derived from it (http -> ws, https -> wss).
//
// Development only: LAMISS_API_URL and LAMISS_GOOGLE_CLIENT_ID (from the shell
// or a git-ignored .env) override the file, for a local or test backend.
// Staging and production never read .env, refuse those variables, and need
// https on a public host. Production is the Chrome Web Store package: its
// manifest loses "key" (the store assigns the extension ID).
const fs = require('fs');
const path = require('path');
const { resolveBuildConfig } = require('./lib/build-config');

const root = path.resolve(__dirname, '..');

const args = process.argv.slice(2);
const envFlag = args.indexOf('--env');
const environmentName = envFlag >= 0 ? args[envFlag + 1] : (process.env.LAMISS_ENV || 'development');
const positional = args.filter((arg, index) => !arg.startsWith('--') && index !== envFlag + 1);

// Optional git-ignored .env next to package.json (KEY=value lines), so a plain
// `npm run build` or `npm test` keeps the same settings. Variables already set
// in the environment win. Never for staging or production builds.
const envFile = path.join(root, '.env');
if (environmentName === 'development' && fs.existsSync(envFile)) {
  process.loadEnvFile(envFile);
}
const outDir = path.resolve(root, positional[0] || 'compiled');

const staticFiles = [
  ['src/popup/popup.html', 'popup/popup.html'],
  ['src/popup/popup.css', 'popup/popup.css'],
  ['src/permission/permission.html', 'permission/permission.html'],
  ['src/chat/chat.html', 'chat/chat.html'],
  ['src/offscreen/offscreen.html', 'offscreen/offscreen.html'],
  ['src/content/lamiss-button.css', 'content/lamiss-button.css'],
  ['src/brand/lamiss-logo.svg', 'brand/lamiss-logo.svg'],
  ['src/brand/lamiss-mark-small.svg', 'brand/lamiss-mark-small.svg'],
  ['src/icons/icon-16.png', 'icons/icon-16.png'],
  ['src/icons/icon-32.png', 'icons/icon-32.png'],
  ['src/icons/icon-48.png', 'icons/icon-48.png'],
  ['src/icons/icon-128.png', 'icons/icon-128.png']
];

function fail(message) {
  console.error(`Lamiss build: ${message}`);
  process.exit(1);
}

function copyFile(source, destination) {
  const from = path.join(root, source);
  if (!fs.existsSync(from)) {
    fail(`missing source file: ${source}`);
  }
  const to = path.join(outDir, destination);
  fs.mkdirSync(path.dirname(to), { recursive: true });
  fs.copyFileSync(from, to);
}

let config;
try {
  config = resolveBuildConfig(JSON.parse(fs.readFileSync(path.join(root, 'config', 'environments.json'), 'utf8')), environmentName, process.env);
} catch (error) {
  fail(error.message);
}
const { apiOrigin, wsOrigin, googleClientId } = config;
if (!googleClientId) {
  console.warn([
    '',
    '********************************************************************',
    '* Lamiss build: no Google client ID (LAMISS_GOOGLE_CLIENT_ID).     *',
    '* The extension builds, but "Sign in with Google" will not work.   *',
    '* See README.md for how to create the OAuth client.                *',
    '********************************************************************',
    ''
  ].join('\n'));
}

fs.mkdirSync(outDir, { recursive: true });
for (const [source, destination] of staticFiles) {
  copyFile(source, destination);
}

fs.mkdirSync(path.join(outDir, 'shared'), { recursive: true });
fs.writeFileSync(path.join(outDir, 'shared', 'lamiss-config.js'), [
  '"use strict";',
  `// Generated by scripts/build.js for the ${config.environment} environment (config/environments.json). Do not edit.`,
  `const LAMISS_ENVIRONMENT = ${JSON.stringify(config.environment)};`,
  `const LAMISS_API_BASE_URL = ${JSON.stringify(apiOrigin)};`,
  `const LAMISS_WS_BASE_URL = ${JSON.stringify(wsOrigin)};`,
  `const LAMISS_GOOGLE_CLIENT_ID = ${JSON.stringify(googleClientId)};`,
  ''
].join('\n'));

// "Hey Lamiss" (Lamiss#85): the wake word files, only when a wake word model
// is available (npm run fetch:wakeword; never committed). Release builds take
// only the real "Hey Lamiss" model; development builds fall back to
// openWakeWord's "hey jarvis", whose non-commercial license forbids release.
// Without a model, nothing is copied: no 14 MB WebAssembly runtime, and the
// popup hides the switch.
const WAKE_WORD_MODELS = [
  { file: 'vendor/openwakeword/hey_lamiss.onnx', phrase: 'Hey Lamiss', developmentOnly: false },
  { file: 'vendor/openwakeword/dev/hey_jarvis_v0.1.onnx', phrase: 'Hey Jarvis', developmentOnly: true }
];
const wakeWord = WAKE_WORD_MODELS.find(model => (!model.developmentOnly || config.environment === 'development')
  && fs.existsSync(path.join(root, model.file)));
const wakeWordFiles = [
  ['vendor/openwakeword/melspectrogram.onnx', 'wakeword/melspectrogram.onnx'],
  ['vendor/openwakeword/embedding_model.onnx', 'wakeword/embedding_model.onnx'],
  ['node_modules/onnxruntime-web/dist/ort.wasm.min.js', 'vendor/onnxruntime/ort.wasm.min.js'],
  ['node_modules/onnxruntime-web/dist/ort-wasm-simd-threaded.mjs', 'vendor/onnxruntime/ort-wasm-simd-threaded.mjs'],
  ['node_modules/onnxruntime-web/dist/ort-wasm-simd-threaded.wasm', 'vendor/onnxruntime/ort-wasm-simd-threaded.wasm'],
  ['src/offscreen/wake-worklet.js', 'offscreen/wake-worklet.js']
];
fs.rmSync(path.join(outDir, 'wakeword'), { recursive: true, force: true });
fs.rmSync(path.join(outDir, 'vendor'), { recursive: true, force: true });
fs.rmSync(path.join(outDir, 'offscreen', 'wake-worklet.js'), { force: true });
if (wakeWord) {
  for (const [source, destination] of wakeWordFiles) {
    copyFile(source, destination);
  }
  copyFile(wakeWord.file, 'wakeword/wake-word.onnx');
  fs.writeFileSync(path.join(outDir, 'wakeword', 'model.json'), `${JSON.stringify({
    phrase: wakeWord.phrase, model: 'wake-word.onnx', threshold: 0.5, developmentOnly: wakeWord.developmentOnly
  }, null, 2)}\n`);
}

const manifest = JSON.parse(fs.readFileSync(path.join(root, 'manifest.json'), 'utf8'));
// onnxruntime-web compiles WebAssembly, which extension pages refuse without this.
if (wakeWord) {
  manifest.content_security_policy = { extension_pages: "script-src 'self' 'wasm-unsafe-eval'; object-src 'self'" };
}
// The fixed key pins the extension ID, which the Google OAuth redirect URI
// (https://<id>.chromiumapp.org/) and the backend's CORS allowlist depend on.
// The Chrome Web Store refuses it: the store item has its own ID.
if (typeof manifest.key !== 'string' || !manifest.key) {
  fail('manifest.json must keep its "key": it fixes the extension ID used for Google sign-in');
}
if (config.chromeWebStore) {
  delete manifest.key;
}
if (!manifest.permissions.includes('identity')) {
  fail('manifest.json must keep the "identity" permission: Google sign-in uses chrome.identity');
}
const backendPermission = `${apiOrigin}/*`;
if (!manifest.host_permissions.includes(backendPermission)) {
  manifest.host_permissions.push(backendPermission);
}
fs.writeFileSync(path.join(outDir, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`);

console.log(`Lamiss build: wrote ${path.relative(root, outDir) || '.'}/ (${config.environment}) for the backend at ${apiOrigin} (${wsOrigin}).`);
console.log(wakeWord
  ? `Lamiss build: wake word "${wakeWord.phrase}"${wakeWord.developmentOnly ? ' (development model, not for release)' : ''}.`
  : 'Lamiss build: no wake word model (npm run fetch:wakeword), "Hey Lamiss" is off in this build.');
